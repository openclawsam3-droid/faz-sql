"""
فلتر السبام — يمنع رسائل القروبات والترويج والرقابة من الوصول للمفروز.
كل رسالة خام تمر هنا أولاً: is_spam=1 تعني لا تدخل التحليل أبداً.
"""
import re


# كلمات تدل على نص قروبي/ترويجي/غير عقاري
SPAM_WORDS = [
    "القروب الرابع", "متاح لشخصين", "رابط القناة", "رابط القروب",
    "انضم للقناة", "انضم لقناتنا", "أدمن", "مدير القروب",
    "إعلان ممول", "برومو", "عرض خاص اليوم", "خصم", "كاش باك",
    "بالتوفيق للجميع", "لا تنسى مشاركة", "تابعنا", "وصلنا",
    "الرجاء إعادة توجيه", "شارك المنشور", "مبروك للفائز",
    "سحب يومي", "مسابقة", "يانصيب", "ربح جائزة",
]


# أنماط أرقام دعوات/روابط قروبات
SPAM_PATTERNS = [
    r"https?://t\.me/\+[A-Za-z0-9]+",   # رابط انضمام لقناة/قروب
    r"@\w+",                            # منشنات/قنوات
    r"التسجيل من خلال الرابط",
    r"ادخلوا الآن",
]


def _norm(t):
    if not t:
        return ""
    t = str(t).lower()
    return (t.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
             .replace("ة", "ه").replace("ى", "ي"))


def is_spam(text):
    """يعيد (True, السبب) إذا كانت الرسالة سبام/قروبي/ترويجي"""
    if not text or len(text.strip()) < 20:
        return True, "نص قصير"

    t = _norm(text)

    # الكلمات الممنوعة
    for w in SPAM_WORDS:
        if _norm(w) in t:
            return True, f"كلمة ممنوعة: {w}"

    # الأنماط
    for p in SPAM_PATTERNS:
        if re.search(p, text, re.IGNORECASE):
            return True, f"نمط ترويجي: {p}"

    # مؤشرات إضافية: رموز كثيرة / أرقام دعوة
    emoji = len(re.findall(r"[\U0001F300-\U0001FAFF\u2600-\u27BF]", text))
    if emoji > 6:
        return True, "إيموجيات مبالغ فيها"

    return False, ""


def is_request(text):
    """طلب (يبحث عن) أم عرض (يملك/يؤجّر)"""
    t = _norm(text)
    REQUEST_WORDS = [
        "مطلوب", "ابحث عن", "أبحث عن", "احتاج", "أحتاج", "نبغي", "نحتاج",
        "ارغب", "أرغب", "من يملك", "عندك", "مستعد", "بشتري", "أشتري",
        "ايجار من", "شقة للايجار مطلوب", "دوّرنا", "نسأل عن",
    ]
    for w in REQUEST_WORDS:
        if _norm(w) in t:
            return True
    return False


if __name__ == "__main__":
    samples = [
        "للبيع شقة 3 غرف حي الروضة جدة 450 الف",
        "مطلوب فيلا للايجار حي الشاطئ مكة",
        "القروب الرابع متاح لشخصين انضم من الرابط t.me/+abc",
    ]
    for s in samples:
        sp, reason = is_spam(s)
        print(f"spam={sp} ({reason}) | طلب={is_request(s)} | {s[:40]}")
